#!/usr/bin/env python3
"""Kernel-checked positive cones for the six initial elements."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'lean/Tetrahedral/NormEleven/PositiveOrbitData.lean'
HEADER = """-- Generated by scripts/generate_positive_orbit_data.py; kernel-checked proofs.
import Tetrahedral.PositiveOrbit
import Tetrahedral.Quartic.D1
import Tetrahedral.Quartic.D2
import Tetrahedral.Quartic.D3
import Tetrahedral.Quartic.D11
import Tetrahedral.Quartic.D66

namespace Tetrahedral.NormEleven
"""
TEMPLATE = """
namespace Positive{d}
open {quartic} R
def cone (x : R) : Prop := ∀ i, 0≤x i
instance (x : R) : Decidable (cone x) :=
  inferInstanceAs (Decidable (∀ i : Fin 4, 0≤x i))
theorem cone_mul (x y : R) (hx : cone x) (hy : cone y) : cone (x*y) := by
  have hx0 := hx 0; have hx1 := hx 1; have hx2 := hx 2; have hx3 := hx 3
  have hy0 := hy 0; have hy1 := hy 1; have hy2 := hy 2; have hy3 := hy 3
  intro i
  fin_cases i
  · change 0≤(x*y) 0
    rw [mul_apply0]; positivity
  · change 0≤(x*y) 1
    rw [mul_apply1]; positivity
  · change 0≤(x*y) 2
    rw [mul_apply2]; positivity
  · change 0≤(x*y) 3
    rw [mul_apply3]; positivity
def tauHom : R →* R where
  toFun := tau
  map_one' := by ext i; fin_cases i <;> rfl
  map_mul' := tau_mul

theorem xi0_nonnegative (i : ℤ) : 0≤(xi0*(↑(rhoU^i):R)) 0 :=
  PositiveOrbit.nonnegative (fun x : R => x 0) tauHom (fun _ => rfl)
    rhoU (by decide +kernel) cone (by decide +kernel) cone_mul
    (fun x hx => hx 0) (by decide +kernel) xi0
    (by decide +kernel) (by decide +kernel) i
{extra}
end Positive{d}
"""
EXTRA = """
theorem xi1_nonnegative (i : ℤ) : 0≤(xi1*(↑(rhoU^i):R)) 0 :=
  PositiveOrbit.nonnegative (fun x : R => x 0) tauHom (fun _ => rfl)
    rhoU (by decide +kernel) cone (by decide +kernel) cone_mul
    (fun x hx => hx 0) (by decide +kernel) xi1
    (by decide +kernel) (by decide +kernel) i
"""


def main():
    parts = [HEADER]
    for d in [1, 2, 3, 11, 66]:
        parts.append(TEMPLATE.format(d=d, quartic='Quartic66' if d == 66 else f'Quartic{d}',
                                     extra=EXTRA if d == 2 else ''))
    parts.append('\nend Tetrahedral.NormEleven\n')
    OUT.write_text(''.join(parts))


if __name__ == '__main__':
    main()
