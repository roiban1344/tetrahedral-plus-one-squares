#!/usr/bin/env python3
"""Kernel-checked real orientation from the norm and trace of Euler factors."""
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'lean/Tetrahedral/NormEleven/PositiveOrbitData.lean'
HEADER = """-- Generated by scripts/generate_positive_orbit_data.py; kernel-checked proofs.
import Tetrahedral.Quartic.D1
import Tetrahedral.Quartic.D2
import Tetrahedral.Quartic.D3
import Tetrahedral.Quartic.D11
import Tetrahedral.Quartic.D66

namespace Tetrahedral.NormEleven
"""
TEMPLATE = """theorem norm_positive (x : R) (hH : relH x=11) (hK : relK x=0)
    (ht : 0<(x 0:ℝ)+(x 1:ℝ)*cR) : 0<sig x ∧0<sig (tau x) := by
  have hp : 0<sig x*sig (tau x) := by rw [sig_tau,hH,hK]; norm_num
  have hh : sig x+sig (tau x)=2*((x 0:ℝ)+(x 1:ℝ)*cR) := by
    simp only [sig,tau_apply0,tau_apply1,tau_apply2,tau_apply3]; push_cast; ring
  exact RelativeUnitGap.positive_pair _ _ hp (by linarith)
theorem xi0_positive : 0<sig xi0 ∧0<sig (tau xi0) :=
  norm_positive xi0 (by decide +kernel) (by decide +kernel) (by
    norm_num [xi0]
    have := cR_pos; positivity)
theorem unit_positive (u : R) (hH : relH u=1) (hK : relK u=0) (hpos : 0<sig u) :
    ∃ i : ℤ, u=(↑(rhoU^i):R) :=
  RelativeUnitGap.positive_power sigHom rhoU (by change sig (-1)= -1; simp [sig])
    (by change 0<Lam; linarith [one_lt_Lam]) u hpos (rel_unit_trace u hH hK)
"""
TAU = """def tauHom : R →* R where
  toFun := tau
  map_one' := by ext i; fin_cases i <;> rfl
  map_mul' := tau_mul

"""
EXTRA = """theorem xi1_positive : 0<sig xi1 ∧0<sig (tau xi1) :=
  norm_positive xi1 (by decide +kernel) (by decide +kernel) (by
    norm_num [xi1]
    have := cR_pos; positivity)
"""
def main():
    parts = [HEADER]
    for d in [1, 2, 3, 11, 66]:
        quartic = 'Quartic66' if d == 66 else f'Quartic{d}'
        parts.append(f'\nnamespace Positive{d}\nopen {quartic} R\n')
        parts.append(TAU)
        parts.append(TEMPLATE)
        if d == 2:
            parts.append(EXTRA)
        parts.append(f'\nend Positive{d}\n')
    parts.append('\nend Tetrahedral.NormEleven\n')
    OUT.write_text(''.join(parts))

if __name__ == '__main__':
    main()
