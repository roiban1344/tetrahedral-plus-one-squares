#!/usr/bin/env python3
"""Instantiate the relative-norm remainder lemma in the five existing orders.

The generated proofs are checked by the Lean kernel; this generator supplies
no assumptions. Running it again reproduces both outputs byte for byte.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "lean/Tetrahedral/NormEleven/NormPrecisionData.lean"

HEADER = """-- Generated by scripts/generate_norm_precision_data.py; kernel-checked proofs.
import Tetrahedral.RelativeNormPrecision
import Tetrahedral.Quartic.D1
import Tetrahedral.Quartic.D2
import Tetrahedral.Quartic.D3
import Tetrahedral.Quartic.D11
import Tetrahedral.Quartic.D66

namespace Tetrahedral.NormEleven
"""

TEMPLATE = """
namespace Precision{d}
open {quartic} R
def X : R →ₗ[ℤ] ℤ where
  toFun x := x 0
  map_add' _ _ := rfl
  map_smul' _ _ := rfl
def Y : R →ₗ[ℤ] ℤ where
  toFun x := x 1
  map_add' _ _ := rfl
  map_smul' _ _ := rfl

theorem mul (y V : R) (hV : ({m}:ℤ) ∣ V 0 ∧ ({m}:ℤ) ∣ V 1) :
    ({m}:ℤ) ∣ (y*V) 0 ∧ ({m}:ℤ) ∣ (y*V) 1 := by
  obtain ⟨a,ha⟩ := hV.1; obtain ⟨b,hb⟩ := hV.2
  simp only [mul_apply0,mul_apply1,ha,hb]
  constructor <;> ring_nf <;> omega

theorem quadratic (y V : R) (hV : ({m}:ℤ) ∣ V 0 ∧ ({m}:ℤ) ∣ V 1) :
    (4:ℤ) ∣ Qf (y*V) := by
  obtain ⟨h0,h1⟩ := mul y V hV
  obtain ⟨a,ha⟩ := h0; obtain ⟨b,hb⟩ := h1
  simp only [Qf,ha,hb]
  ring_nf; omega

theorem norm (V : R) (hV : ({m}:ℤ) ∣ V 0 ∧ ({m}:ℤ) ∣ V 1) :
    ({m}:ℤ) ∣ relH V ∧ ({m}:ℤ) ∣ relK V := by
  obtain ⟨a,ha⟩ := hV.1; obtain ⟨b,hb⟩ := hV.2
  simp only [relH,relK,ha,hb]
  constructor <;> ring_nf <;> omega

def centre : Fin {count} → ℤ := ![{centres}]
def point : Fin {count} → R := ![{points}]
theorem point_eq : ∀ c : Fin {count}, xi0*(↑(rhoU^(centre c)):R)=point c := by decide +kernel

theorem linear (c : Fin {count}) (E : R)
    (hE : ({m}:ℤ) ∣ E 0 ∧ ({m}:ℤ) ∣ E 1) :
    (8:ℤ) ∣ Lf (xi0*(↑(rhoU^(centre c)):R)) ((xi0*(↑(rhoU^(centre c)):R))*E) := by
  obtain ⟨a,ha⟩ := hE.1; obtain ⟨b,hb⟩ := hE.2
  rw [point_eq c]
  fin_cases c <;> norm_num [point,Lf,mul_apply0,mul_apply1,ha,hb] <;> ring_nf <;> omega

theorem error (t : ℕ) (ht : ({m}:ℤ) ∣ 2^t) (w : Rˣ) (U : R)
    (hw : (w:R)=1+2^(t+1)*U)
    (hrel : ∀ i : ℤ, relH (↑(w^i):R)=1 ∧ relK (↑(w^i):R)=0)
    (k : ℕ) (a : ℤ) (E : R)
    (he : (↑(w^((2:ℤ)^k*a)):R)=1+2^(k+t+1)*((a:R)*U+2^t*E)) :
    ({m}:ℤ) ∣ E 0 ∧ ({m}:ℤ) ∣ E 1 := by
  apply RelativeNormPrecision.power_error_dvd X Y relH relK ?_ ?_ {m} t ht ?_ w U hw hrel k a E he
  · intro q V
    change relH (1+(2*q) • V)=1+4*q*V 0+4*q^2*relH V
    simp only [relH,add_apply,zsmul_apply,one_apply]; simp; ring
  · intro q V
    change relK (1+(2*q) • V)=4*q*V 1+4*q^2*relK V
    simp only [relK,add_apply,zsmul_apply,one_apply]; simp; ring
  · intro V hx hy
    change ({m}:ℤ) ∣ V 0 at hx
    change ({m}:ℤ) ∣ V 1 at hy
    exact norm V ⟨hx,hy⟩
end Precision{d}
"""


PARITY_HEADER = '-- Generated by scripts/generate_norm_precision_data.py; kernel-checked proofs.\nimport Tetrahedral.NormEleven.DyadicSimple\nimport Tetrahedral.NormEleven.NormPrecisionData\n\n/-! Two parity classes and norm-constrained remainders replace the old\npositive-phase certificates for d=1,3,11. -/\nset_option maxRecDepth 10000\nset_option maxHeartbeats 0\n\nnamespace Tetrahedral.NormEleven\n'
PARITY_TEMPLATE = '\nnamespace Dyadic{d}\nopen Quartic{d} R\ndef step : R := ⟨fun i => ((rho^2-1 : R) i)/4⟩\ntheorem step_eq : (↑(rhoU^2):R)=1+4*step := by\n  have h : (↑(rhoU^2):R)=1+(4:ℤ) • step := by\n    ext i; fin_cases i <;> decide +kernel\n  simpa only [zsmul_eq_mul,Int.cast_ofNat] using h\n\ntheorem roots (m : ℤ) (hm : f (xi0*(↑(rhoU^m):R))=0) : m=0 ∨ m= -1 := by\n  apply DyadicSimple.pair f rhoU xi0 ?_ m hm\n  intro c i hi\n  have hr : ∀ j : ℤ, relH (↑((rhoU^2)^j):R)=1 ∧ relK (↑((rhoU^2)^j):R)=0 := by\n    intro j; have h := relN_rho_zpow (2*j); rwa [zpow_mul,zpow_ofNat] at h\n  have hz : ∀ c : Fin 2, f (xi0*(↑(rhoU^(DyadicSimple.centre c)):R))=0 := by decide +kernel\n  have hk : ∀ c : Fin 2, Lf (xi0*(↑(rhoU^(DyadicSimple.centre c)):R))\n      ((xi0*(↑(rhoU^(DyadicSimple.centre c)):R))*step)%16=8 := by decide +kernel\n  apply RelativeNormPrecision.unique Precision{d}.X Precision{d}.Y 2 f\n    (Lf (xi0*(↑(rhoU^(DyadicSimple.centre c)):R))) Qf\n    (xi0*(↑(rhoU^(DyadicSimple.centre c)):R)) (rhoU^2) 1 step\n    (by norm_num; exact step_eq) (hz c) (f_expand _)\n    (Precision{d}.error 1 (by decide) (rhoU^2) step (by norm_num; exact step_eq) hr)\n    (by decide +kernel) (Precision{d}.linear c) (Precision{d}.quadratic _) ?_ i hi\n  intro a ha\n  norm_num at ha\n  have h := Int.emod_eq_zero_of_dvd ha\n  rw [Int.mul_emod,hk c] at h\n  omega\n\ntheorem negative (m : ℤ) : f (-(xi0*(↑(rhoU^m):R)))≠0 :=\n  DyadicSimple.negative f Lf Qf f_expand rhoU xi0 step step_eq\n    (by decide +kernel) (by decide +kernel) m\nend Dyadic{d}\n'

def main():
    parts = [HEADER]
    data = {
        1: ([0, -1], [[1, 1, 5, -2], [25, 9, -5, 0]]),
        2: ([0, -4, -1], [[2, 1, 2, -1], [13778, 7953, -2158, -1245], [8, 3, -2, 0]]),
        3: ([0, -1], [[3, 1, 1, 0], [27, 17, -9, -6]]),
        11: ([0, -1], [[11, 1, 1, 0], [11, 1, -1, 0]]),
        66: ([1, -1], [[66, 19, 0, 1], [66, 19, 0, -1]]),
    }
    for d, m, quartic in [(1, 2, "Quartic1"), (2, 4, "Quartic2"), (3, 2, "Quartic3"),
                       (11, 2, "Quartic11"), (66, 4, "Quartic66")]:
        centres, points = data[d]
        parts.append(TEMPLATE.format(d=d, m=m, quartic=quartic, count=len(centres),
            centres=','.join(map(str, centres)),
            points=','.join('⟨!['+','.join(map(str, p))+']⟩' for p in points)))
    parts.append("\nend Tetrahedral.NormEleven\n")
    OUT.write_text("".join(parts))
    parity = PARITY_HEADER + ''.join(PARITY_TEMPLATE.format(d=d) for d in [1, 3, 11])
    parity += '\nend Tetrahedral.NormEleven\n'
    (OUT.parent / 'DyadicCertificates.lean').write_text(parity)


if __name__ == "__main__":
    main()
