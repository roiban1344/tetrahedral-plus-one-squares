#!/usr/bin/env python3
"""Generate exact polynomial obstructions for the short d=2,66 phases.

Every identity includes all integer exponents and all error coordinates;
the output is a Lean proof, not an assumption made by this generator.
"""
from pathlib import Path
from norm11_dyadic_probe import read_ring, vector

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "lean/Tetrahedral/NormEleven/TaylorObstructions.lean"
HEADER = """-- Generated by scripts/generate_taylor_obstructions.py; kernel-checked identities.
import Tetrahedral.TaylorOrbit
import Tetrahedral.NormEleven.FactoredDirectionData

set_option maxRecDepth 20000
set_option maxHeartbeats 0
namespace Tetrahedral.NormEleven
"""
TEMPLATE = """
namespace Obstruction{d}
open {quartic} R
def point : Fin {count} → R := ![{points}]
def first : Fin {count} → R := ![{first}]
def second : Fin {count} → R := ![{second}]
def third : Fin {count} → R := ![{third}]
def modulus : Fin {count} → ℤ := ![{moduli}]
def value : Fin {count} → ℤ := ![{values}]
theorem first_eq : ∀ j : Fin {count}, point j*Direction{d}.step=first j := by decide +kernel
theorem second_eq : ∀ j : Fin {count}, point j*Direction{d}.step^2=second j := by decide +kernel
theorem third_eq : ∀ j : Fin {count}, point j*Direction{d}.step^3=third j := by decide +kernel

def model (j : Fin {count}) (a : ℤ) (E : R) : R := ⟨fun i => point j i+
  {delta}*a*first j i+{halfDelta}*a*(a-1)*second j i+{cube}*(third j*E) i⟩
theorem model_eq (j : Fin {count}) (a : ℤ) (E : R) :
    TaylorOrbit.truncation {s} Direction{d}.step (point j) a E=model j a E := by
  simp only [TaylorOrbit.truncation]
  rw [first_eq j,second_eq j,third_eq j]
  ext i
  simp only [model,add_apply,zsmul_apply]
  ring

theorem residue (j : Fin {count}) (a : ℤ) (E : R) :
    modulus j ∣ f (model j a E)-value j := by
  fin_cases j <;> norm_num [modulus,value,f,model,point,first,second,third,mul_apply0,mul_apply1]
    <;> ring_nf <;> omega
theorem value_nonzero : ∀ j : Fin {count}, ¬ modulus j ∣ value j := by decide +kernel
theorem nonzero (j : Fin {count}) (a : ℤ) (E : R) :
    f (TaylorOrbit.truncation {s} Direction{d}.step (point j) a E)≠0 := by
  rw [model_eq]
  intro h
  have hd := residue j a E
  rw [h,zero_sub] at hd
  exact value_nonzero j (dvd_neg.mp hd)
end Obstruction{d}
"""


def vec(v):
    return '⟨![' + ','.join(map(str, v)) + ']⟩'


def main():
    parts = [HEADER]
    archive = [HEADER]
    specs = [(2, 3, 8, 'Quartic2', [(1, r) for r in [1, 2, 3, 5, 6]]),
             (66, 11, 4, 'Quartic66', [(1, 2)]),
             (66, 11, 4, 'Quartic66', [(1, 2), (-1, 1), (-1, 2), (-1, 3)])]
    for d, e, delta, quartic, cases in specs:
        ring, raw = read_ring(d)
        big = 2**4096

        def mul(x, y):
            return tuple(v if v < big//2 else v-big for v in raw(x, y, big))

        rho = vector('rho', ring)
        xi = vector('xi0', (ROOT/f'lean/Tetrahedral/Quartic/D{d}.lean').read_text())

        def power(n):
            x = (1, 0, 0, 0)
            for _ in range(n):
                x = mul(x, rho)
            return x

        step = tuple((x-(i == 0))//delta for i, x in enumerate(power(delta)))
        step2, step3 = mul(step, step), mul(mul(step, step), step)
        rows, ns, vs = [], [], []
        for sg, r in cases:
            y = mul(tuple(sg*v for v in xi), power(r))
            z, v, w = mul(y, step), mul(y, step2), mul(y, step3)
            f = (y[0]-3)**2-e*y[1]**2+2
            L = 2*(y[0]-3)*z[0]-2*e*y[1]*z[1]
            L2 = 2*(y[0]-3)*v[0]-2*e*y[1]*v[1]
            A = delta*L-delta**2//2*L2
            B = delta**2//2*L2+delta**2*(z[0]**2-e*z[1]**2)
            for k in range(1, 21):
                N = 2**k
                if f % N and A % N == 0 and B % N == 0:
                    break
            else:
                raise ValueError(f'No polynomial obstruction for {d}, {sg}, {r}')
            rows.append((y, z, v, w)); ns.append(N); vs.append(f % N)
            print(d, sg, r, 'modulus', N, 'constant residue', f % N)
        rendered = TEMPLATE.format(d=d, quartic=quartic, count=len(rows),
            points=','.join(vec(row[0]) for row in rows),
            first=','.join(vec(row[1]) for row in rows),
            second=','.join(vec(row[2]) for row in rows),
            third=','.join(vec(row[3]) for row in rows),
            moduli=','.join(map(str, ns)), values=','.join(map(str, vs)),
            delta=delta, halfDelta=delta**2//2, cube=delta**3, s=delta//4)
        if d==66:
            archive.append(rendered.replace("Obstruction66", "Obstruction66Signed")
                           if len(cases)>1 else rendered)
        else:
            parts.append(rendered)
    parts.append('\nend Tetrahedral.NormEleven\n')
    OUT.write_text(''.join(parts))
    archive.append('\nend Tetrahedral.NormEleven\n')
    OUT.with_name('SignedTaylorArchive.lean').write_text(''.join(archive))


if __name__ == '__main__':
    main()
