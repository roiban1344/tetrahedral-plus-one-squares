#!/usr/bin/env python3
"""Generate kernel-checked direction arithmetic, not assumed certificates."""
from pathlib import Path
from norm11_dyadic_probe import read_ring, vector

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "lean/Tetrahedral/NormEleven/FactoredDirectionData.lean"
HEADER = """-- Generated by scripts/generate_factored_direction_data.py; kernel-checked proofs.
import Tetrahedral.FactoredExponent
import Tetrahedral.Quartic.D1
import Tetrahedral.Quartic.D2
import Tetrahedral.Quartic.D3
import Tetrahedral.Quartic.D11
import Tetrahedral.Quartic.D66

set_option maxRecDepth 20000
set_option maxHeartbeats 0
namespace Tetrahedral.NormEleven
"""
TEMPLATE = """
namespace Direction{d}
open {quartic} R
-- The direction is (rho^{P}-1)/{delta}, as checked by step_eq.
def step : R := {step}
def squarePart : R := {half}
def square : R := {square}
theorem square_value : step^2=square := by decide +kernel
theorem step_eq : (↑(rhoU^{P}):R)=1+{delta}*step := by
  have h : (↑(rhoU^{P}):R)=1+({delta}:ℤ) • step := by
    ext i; fin_cases i <;> decide +kernel
  simpa only [zsmul_eq_mul,Int.cast_ofNat] using h
theorem square_eq : step^2=2*{factor}*squarePart := by
  have h : step^2=({squareFactor}:ℤ) • squarePart := by
    ext i; fin_cases i <;> decide +kernel
  calc step^2=({squareFactor}:ℤ) • squarePart := h
       _=2*{factor}*squarePart := by rw [zsmul_eq_mul]; push_cast; ring

def centre : Fin {count} → ℤ := ![{centres}]
def point : Fin {count} → R := ![{points}]
theorem point_eq : ∀ c : Fin {count}, xi0*(↑({orbit}^(centre c)):R)=point c := by decide +kernel
def first : Fin {count} → R := ![{first}]
def tangent : Fin {count} → R := ![{tangent}]
theorem first_eq : ∀ c : Fin {count}, point c*step=first c := by decide +kernel
theorem tangent_eq : ∀ c : Fin {count}, point c*step^2=tangent c := by decide +kernel
def residue (b : ℤ) (E : R) : R := ⟨![b+2*E 0,2*E 1,2*E 2,2*E 3]⟩
theorem residue_eq (b : ℤ) (E : R) : residue b E=b • (1:R)+(2:ℤ) • E := by
  ext i; fin_cases i <;> simp only [residue,add_apply,zsmul_apply,one_apply] <;> norm_num
def combine (a : ℤ) (F : R) (b : ℤ) (G : R) : R := ⟨fun i => a*F i+b*G i⟩
theorem combine_eq (a : ℤ) (F : R) (b : ℤ) (G : R) : combine a F b G=a • F+b • G := by
  ext i; rfl

theorem linear (c : Fin {count}) (b : ℤ) (E : R) :
    ({N}:ℤ) ∣ {q}*Lf (point c)
      (tangent c*residue b E) := by
  fin_cases c <;> norm_num [point,tangent,Lf,mul_apply0,mul_apply1,
    residue] <;> ring_nf <;> omega

theorem quadratic (c : Fin {count}) (a b : ℤ) (E : R) :
    ({N}:ℤ) ∣ {delta}*Qf
      (combine a (first c) {q} (tangent c*residue b E)) := by
  fin_cases c <;> norm_num [first,tangent,Qf,mul_apply0,mul_apply1,
    combine,residue] <;> ring_nf <;> omega

theorem unique (c : Fin {count}) (i : ℤ)
    (hi : f ((xi0*(↑({orbit}^(centre c)):R))*(↑((rhoU^{P})^i):R))=0) : i=0 := by
  rw [point_eq c] at hi
  have hz : ∀ c : Fin {count}, f (point c)=0 := by decide +kernel
  have hk : ∀ c : Fin {count}, Lf (point c) (first c)%{N} ∈ [{quarter},{halfN},{three}] := by decide +kernel
  apply FactoredExponent.unique f (Lf (point c)) Qf
    (point c) (rhoU^{P}) {t} {v} (by decide) step
    (by simpa only [Nat.reduceAdd,show (2:R)^({t}+1)={delta} by ring] using step_eq)
    (hz c) (f_expand _) (first c) (tangent c) (first_eq c) (tangent_eq c)
    ?_ ?_ ?_ i hi
  · intro b E
    have hh := linear c b E
    rw [residue_eq] at hh
    simpa only [Int.reducePow,zsmul_eq_mul,Int.cast_ofNat,mul_one] using hh
  · intro a b E
    have hh := quadratic c a b E
    rw [combine_eq,residue_eq] at hh
    simpa only [Nat.reduceAdd,Int.reducePow,zsmul_eq_mul,Int.cast_ofNat,mul_one] using hh
  · intro a ha
    norm_num at ha
    have hm := Int.emod_eq_zero_of_dvd ha
    rw [Int.mul_emod] at hm
    have h := hk c
    simp only [List.mem_cons,List.not_mem_nil,or_false] at h
    rcases h with h|h|h <;> rw [h] at hm <;> omega
end Direction{d}
"""


PARITY_HEADER = """-- Generated by scripts/generate_factored_direction_data.py; kernel-checked proofs.
import Tetrahedral.NormEleven.DyadicSimple
import Tetrahedral.NormEleven.LatticeDirectionData

namespace Tetrahedral.NormEleven
"""
PARITY_TEMPLATE = """
namespace Dyadic{d}
open Quartic{d} R
abbrev step : R := Local{d}.step
theorem step_eq : (↑(rhoU^2):R)=1+4*step := Local{d}.step_eq
theorem roots (m : ℤ) (hm : f (xi0*(↑(rhoU^m):R))=0) : m=0 ∨ m= -1 :=
  DyadicSimple.pair f rhoU xi0 Local{d}.unique m hm
end Dyadic{d}
"""

def vec(v):
    return '⟨![' + ','.join(map(str, v)) + ']⟩'


def main():
    points = {
        1: ([0, -1], [[1, 1, 5, -2], [25, 9, -5, 0]]),
        2: ([0, -1], [[2, 1, 2, -1], [13778, 7953, -2158, -1245]]),
        3: ([0, -1], [[3, 1, 1, 0], [27, 17, -9, -6]]),
        11: ([0, -1], [[11, 1, 1, 0], [11, 1, -1, 0]]),
        66: ([1, -1], [[66, 19, 0, 1], [66, 19, 0, -1]]),
        '2Odd': ([-1], [[8, 3, -2, 0]]),
    }
    parts = [HEADER]
    for d, P, delta, t, v, quartic in [(1, 2, 4, 1, 4, 'Quartic1'), (2, 8, 8, 2, 7, 'Quartic2'),
        (3, 2, 4, 1, 4, 'Quartic3'), (11, 2, 4, 1, 4, 'Quartic11'), (66, 4, 4, 1, 6, 'Quartic66'),
        ('2Odd', 4, 4, 1, 6, 'Quartic2')]:
        ring, mul = read_ring(2 if d == '2Odd' else d)
        rho = vector('rho', ring)
        w = (1, 0, 0, 0)
        for _ in range(P):
            w = mul(w, rho, 2**4096)
        step = tuple((x - (i == 0)) // delta for i, x in enumerate(w))
        sq = mul(step, step, 2**4096)
        squareFactor = 4 if d in [2, 66] else 2
        assert all(x % squareFactor == 0 for x in sq)
        cs, ps = points[d]
        N = 2**v
        parts.append(TEMPLATE.format(d=d, P=P, delta=delta, t=t, v=v, quartic=quartic,
            orbit="(rhoU^4)" if d==2 else "rhoU",
            step=vec(step), half=vec([x // squareFactor for x in sq]), square=vec(sq),
            squareFactor=squareFactor, factor=squareFactor//2, count=len(cs),
            centres=','.join(map(str, cs)), points=','.join(map(vec, ps)),
            first=','.join(vec(mul(p, step, 2**4096)) for p in ps),
            tangent=','.join(vec(mul(p, sq, 2**4096)) for p in ps),
            N=N, q=2**t, quarter=N//4, halfN=N//2, three=3*N//4))
    parts.append('\nend Tetrahedral.NormEleven\n')
    OUT.write_text(''.join(parts))
    parity = PARITY_HEADER + ''.join(PARITY_TEMPLATE.format(d=d) for d in [1, 3, 11])
    parity += '\nend Tetrahedral.NormEleven\n'
    (OUT.parent / 'DyadicCertificates.lean').write_text(parity)


if __name__ == '__main__':
    main()
