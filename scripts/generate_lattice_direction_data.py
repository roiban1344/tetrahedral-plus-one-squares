#!/usr/bin/env python3
"""Generate small lattice certificates; all finite checks run in the Lean kernel."""
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT/'lean/Tetrahedral/NormEleven/LatticeDirectionData.lean'
HEADER = """-- Generated by scripts/generate_lattice_direction_data.py; kernel-checked.
import Tetrahedral.LatticeExponent
import Tetrahedral.Quartic.D1
import Tetrahedral.Quartic.D2
import Tetrahedral.Quartic.D3
import Tetrahedral.Quartic.D11
import Tetrahedral.Quartic.D66

set_option maxRecDepth 20000
set_option maxHeartbeats 0
namespace Tetrahedral.NormEleven
"""
COORD = """
namespace Coordinate{d}
open {quartic} R
def coord (j : Fin 4) : R →ₗ[ℤ] ℤ where
  toFun x := x j
  map_add' _ _ := rfl
  map_smul' _ _ := rfl
def basis (j : Fin 4) : R := ⟨fun i => if i=j then 1 else 0⟩
theorem repr (E : R) : E=∑ j : Fin 4, E j • basis j := by
  rw [Fin.sum_univ_four]
  ext i; fin_cases i <;> simp only [basis,add_apply,zsmul_apply] <;> norm_num
end Coordinate{d}
"""
LOCAL = """
namespace Local{label}
open {quartic} R Coordinate{d}
-- The direction and centres are defined by the actual unit powers.
def step : R := ⟨fun i => ((↑(rhoU^{P}):R) i-(if i=0 then 1 else 0))/{delta}⟩
theorem step_eq : (↑(rhoU^{P}):R)=1+{delta}*step := by
  have h : (↑(rhoU^{P}):R)=1+({delta}:ℤ) • step := by
    ext i; fin_cases i <;> decide +kernel
  simpa only [zsmul_eq_mul,Int.cast_ofNat] using h
theorem square_dvd : ∀ j : Fin 4, ({m}:ℤ) ∣ (step^2) j := by decide +kernel
def centre : Fin {count} → ℤ := ![{centres}]
def point (c : Fin {count}) : R := xi0*(↑({orbit}^(centre c)):R)
def first (c : Fin {count}) : R := point c*step
def tangent (c : Fin {count}) : R := point c*step^2

/-- Two coordinates, one scalar bit, and the four columns of a linear map.
No polynomial in arbitrary error coordinates is expanded. -/
theorem certificate : ∀ c : Fin {count},
    f (point c)=0 ∧ {m} ∣ coord 0 (first c) ∧ {m} ∣ coord 1 (first c) ∧
    {scalar} ∣ Lf (point c) (tangent c) ∧
    {N} ∣ Lf (point c) (first c)-{H} ∧
    ∀ j : Fin 4, {square} ∣ Lf (point c) (tangent c*basis j) := by
  decide +kernel

theorem unique (c : Fin {count}) (i : ℤ)
    (hi : f ((xi0*(↑({orbit}^(centre c)):R))*(↑((rhoU^{P})^i):R))=0) : i=0 := by
  obtain ⟨hz,hA,hB,hs,hd,hcols⟩ := certificate c
  exact LatticeExponent.unique f (Lf (point c)) Qf (coord 0) (coord 1) {e}
    (point c) (rhoU^{P}) {t} {v} (by decide) step
    (by simpa only [Nat.reduceAdd,show (2:R)^({t}+1)={delta} by ring] using step_eq)
    hz (f_expand _) (fun _ => rfl) {m} (by decide) (by norm_num)
    (first c) (tangent c) rfl rfl basis (fun E j => E j) repr
    ⟨hA,hB⟩ hs square_dvd hcols hd i hi
end Local{label}
"""

def main():
    parts = [HEADER]
    for d in [1,2,3,11,66]:
        quartic = 'Quartic66' if d==66 else f'Quartic{d}'
        parts.append(COORD.format(d=d,quartic=quartic))
    specs = [(1,1,2,4,1,4,2,6,[0,-1]),(2,2,8,8,2,7,4,3,[0,-1]),
             (3,3,2,4,1,4,2,2,[0,-1]),(11,11,2,4,1,4,2,66,[0,-1]),
             (66,66,4,4,1,6,4,11,[1,-1]),('2Odd',2,4,4,1,6,4,3,[-1])]
    for label,d,P,delta,t,v,m,e,centres in specs:
        parts.append(LOCAL.format(label=label,d=d,P=P,delta=delta,t=t,v=v,m=m,e=e,
            quartic='Quartic66' if d==66 else f'Quartic{d}', count=len(centres),
            centres=','.join(map(str,centres)),orbit='(rhoU^4)' if label==2 else 'rhoU',
            scalar=2*m*m,N=2**v,H=2**(v-1),square=m*m))
    parts.append('\nend Tetrahedral.NormEleven\n')
    OUT.write_text(''.join(parts))

if __name__ == '__main__':
    main()
